'use client';

import { useEffect, useRef, useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { Send, MessageSquare, Loader2 } from 'lucide-react';
import { Button } from '../ui/Button';
import { Skeleton } from '../ui/States';
import {
  fetchTradeMessages,
  sendTradeMessage,
  tradeErrorMessage,
  type TradeMessage,
  type TradeParty,
} from '../../lib/services/trade';
import { cn, formatDateTime } from '../../lib/utils';

function senderId(sender: TradeMessage['sender']): string | null {
  if (!sender) return null;
  return typeof sender === 'string' ? sender : sender._id;
}

function senderName(sender: TradeMessage['sender']): string {
  if (!sender) return 'Unknown';
  if (typeof sender === 'string') return sender;
  return (sender as TradeParty).fullName || 'Unknown';
}

/**
 * Trade chat.
 *
 * Reads from the REST endpoint; the socket (useTradeSocket) invalidates the same query
 * key on `new_message`, so a message from the other party appears without a poll.
 *
 * System messages are generated by the server on state changes (dispute raised, trade
 * completed) and are deliberately styled as records, not speech — they are the ledger
 * speaking, not a person.
 */
export function ChatPanel({
  tradeId,
  currentUserId,
  disabled,
}: {
  tradeId: string;
  currentUserId?: string;
  /** Set while a dispute is open: the room stays readable, but talking is paused. */
  disabled?: boolean;
}) {
  const queryClient = useQueryClient();
  const [draft, setDraft] = useState('');
  const [sendError, setSendError] = useState<string | null>(null);
  const scrollRef = useRef<HTMLDivElement>(null);

  const { data: messages = [], isLoading, isError } = useQuery({
    queryKey: ['trade', tradeId, 'messages'],
    queryFn: () => fetchTradeMessages(tradeId),
    // The socket is the primary transport; this is a slow safety net for a dropped socket.
    refetchInterval: 30_000,
  });

  const sendMutation = useMutation({
    mutationFn: (content: string) => sendTradeMessage(tradeId, content),
    onSuccess: () => {
      setDraft('');
      setSendError(null);
      queryClient.invalidateQueries({ queryKey: ['trade', tradeId, 'messages'] });
    },
    onError: (error) => {
      // Keep the draft so the user does not retype it.
      setSendError(tradeErrorMessage(error, 'Message did not send. Try again.'));
    },
  });

  // Follow the conversation: jump to the newest message whenever the list grows.
  useEffect(() => {
    const node = scrollRef.current;
    if (!node) return;
    node.scrollTop = node.scrollHeight;
  }, [messages.length]);

  const submit = () => {
    const content = draft.trim();
    if (!content || sendMutation.isPending) return;
    sendMutation.mutate(content);
  };

  return (
    <section
      aria-label="Trade chat"
      className="flex h-[min(32rem,70vh)] flex-col rounded-card border border-neutral-200 bg-white shadow-card"
    >
      <header className="flex items-center gap-2 border-b border-neutral-100 px-4 py-3">
        <MessageSquare className="h-4 w-4 text-neutral-400" aria-hidden="true" />
        <h2 className="font-display text-sm font-semibold text-ink">Messages</h2>
      </header>

      <div ref={scrollRef} className="flex-1 space-y-3 overflow-y-auto px-4 py-4">
        {isLoading && (
          <div className="space-y-3">
            <Skeleton className="h-12 w-2/3" />
            <Skeleton className="ml-auto h-10 w-1/2" />
            <Skeleton className="h-16 w-3/4" />
          </div>
        )}

        {isError && (
          <p className="py-8 text-center text-sm text-clay-600">
            Messages did not load. The rest of the trade still works.
          </p>
        )}

        {!isLoading && !isError && messages.length === 0 && (
          <p className="py-8 text-center text-sm text-neutral-400">
            No messages yet. Agree the details here before anyone moves money.
          </p>
        )}

        {messages.map((message) => {
          if (message.type === 'system') {
            return (
              <div key={message._id} className="flex justify-center">
                <p className="rounded-full bg-neutral-100 px-3 py-1 text-center text-2xs text-neutral-600">
                  {message.content}
                  <span className="ml-2 text-neutral-400">{formatDateTime(message.createdAt)}</span>
                </p>
              </div>
            );
          }

          const mine = senderId(message.sender) === currentUserId;
          return (
            <div key={message._id} className={cn('flex', mine ? 'justify-end' : 'justify-start')}>
              <div className={cn('max-w-[85%]', mine && 'ml-auto text-right')}>
                {!mine && (
                  <p className="mb-0.5 text-2xs font-medium text-neutral-500">
                    {senderName(message.sender)}
                  </p>
                )}
                <div
                  className={cn(
                    'whitespace-pre-wrap break-words rounded-card px-3.5 py-2 text-sm leading-5',
                    mine
                      ? 'bg-forest text-white'
                      : 'border border-neutral-200 bg-neutral-50 text-ink'
                  )}
                >
                  {message.content}
                </div>
                <p className="tnum mt-0.5 text-[10px] text-neutral-400">
                  {formatDateTime(message.createdAt)}
                </p>
              </div>
            </div>
          );
        })}
      </div>

      <div className="border-t border-neutral-100 p-3">
        {disabled ? (
          <p className="rounded-control bg-ochre-50 px-3 py-2.5 text-center text-xs text-ochre-600">
            Chat is read-only while a dispute is open. An admin can see this conversation.
          </p>
        ) : (
          <form
            onSubmit={(event) => {
              event.preventDefault();
              submit();
            }}
            className="flex items-end gap-2"
          >
            <label htmlFor="chat-draft" className="sr-only">
              Write a message
            </label>
            <textarea
              id="chat-draft"
              value={draft}
              onChange={(event) => setDraft(event.target.value)}
              onKeyDown={(event) => {
                if (event.key === 'Enter' && !event.shiftKey) {
                  event.preventDefault();
                  submit();
                }
              }}
              rows={1}
              placeholder="Write a message"
              className="max-h-28 min-h-[44px] flex-1 resize-none rounded-control border border-neutral-300 px-3 py-2.5 text-sm text-ink placeholder:text-neutral-400 focus:border-forest focus:outline-none focus:ring-2 focus:ring-forest/30"
            />
            <Button
              type="submit"
              size="md"
              isPending={sendMutation.isPending}
              disabled={!draft.trim()}
              aria-label="Send message"
            >
              {sendMutation.isPending ? (
                <Loader2 className="h-4 w-4 animate-spin" />
              ) : (
                <Send className="h-4 w-4" />
              )}
            </Button>
          </form>
        )}
        {sendError && (
          <p role="alert" className="mt-2 text-xs font-medium text-clay-600">
            {sendError}
          </p>
        )}
      </div>
    </section>
  );
}
